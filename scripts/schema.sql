CREATE TABLE emergency.fall_types (
    fall_type_id smallint GENERATED BY DEFAULT AS IDENTITY,
    name character varying(50) NOT NULL,
    description character varying(255) NOT NULL,
    severity_level smallint NOT NULL,
    CONSTRAINT pk_fall_types PRIMARY KEY (fall_type_id)
);

CREATE TABLE emergency.outbox_messages (
    emergency_outbox_message_id bigint GENERATED BY DEFAULT AS IDENTITY,
    type character varying(500) NOT NULL,
    payload jsonb NOT NULL,
    occurred_on timestamptz NOT NULL,
    processed_on timestamptz,
    error character varying(2000),
    retry_count integer NOT NULL DEFAULT 0,
    CONSTRAINT pk_emergency_outbox_messages PRIMARY KEY (emergency_outbox_message_id)
);

CREATE TABLE emergency.emergency_incidents (
    emergency_incident_id bigint GENERATED BY DEFAULT AS IDENTITY,
    incident_key uuid NOT NULL,
    device_id bigint NOT NULL,
    patient_id bigint NOT NULL,
    fall_type_id smallint NOT NULL,
    status character varying(50) NOT NULL,
    opened_at timestamptz NOT NULL,
    last_signal_at timestamptz NOT NULL,
    cancelled_at timestamptz,
    resolved_at timestamptz,
    closed_at timestamptz,
    closed_by_user_id bigint,
    ai_confidence_score numeric(5,4),
    latitude numeric(9,6),
    longitude numeric(9,6),
    address character varying(500),
    cancellation_reason character varying(80),
    final_observation character varying(500),
    last_source_payload jsonb,
    CONSTRAINT pk_emergency_incidents PRIMARY KEY (emergency_incident_id),
    CONSTRAINT fk_emergency_incidents_fall_types_fall_type_id FOREIGN KEY (fall_type_id) REFERENCES emergency.fall_types (fall_type_id) ON DELETE RESTRICT
);

